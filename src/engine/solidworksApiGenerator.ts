  return `// ******************************************************************************
// CADVANTA VIRA AI -> SOLIDWORKS C# .NET API AUTOMATION
// Model: ${part.name}
// Generated by: VIRA AI (Lead Architect: Viraj Bansod)
// References: SolidWorks.Interop.sldworks, SolidWorks.Interop.swconst
// ******************************************************************************

using System;
using System.Runtime.InteropServices;
using SolidWorks.Interop.sldworks;
using SolidWorks.Interop.swconst;

namespace CadvantaSolidWorksBridge
{
    public class ViraModelGenerator
    {
        [STAThread]
        public static void Main(string[] args)
        {
            Console.WriteLine("==================================================");
            Console.WriteLine("  CADVANTA VIRA AI -> SolidWorks API Dispatcher   ");
            Console.WriteLine("  Model: ${part.name}                             ");
            Console.WriteLine("==================================================");

            SldWorks swApp = null;
            try
            {
                // 1. Connect to Active Running SolidWorks Instance via COM
                Console.WriteLine("[*] Connecting to SolidWorks COM runtime...");
                swApp = (SldWorks)Marshal.GetActiveObject("SldWorks.Application");
            }
            catch (COMException)
            {
                Console.WriteLine("[!] SolidWorks is not running. Launching new background instance...");
                Type swType = Type.GetTypeFromProgID("SldWorks.Application");
                swApp = (SldWorks)Activator.CreateInstance(swType);
                swApp.Visible = true;
            }

            if (swApp == null)
            {
                Console.WriteLine("[-] Error: Unable to bind to SolidWorks Application.");
                return;
            }

            Console.WriteLine("[+] Connected to SolidWorks " + swApp.RevisionNumber());

            // 2. Create New Part Document from Default Template
            string defaultTemplate = swApp.GetUserPreferenceStringValue((int)swUserPreferenceStringValue_e.swDefaultTemplatePart);
            if (string.IsNullOrEmpty(defaultTemplate))
            {
                defaultTemplate = @"C:\\ProgramData\\SolidWorks\\SOLIDWORKS 2024\\templates\\Part.prtdot";
            }

            ModelDoc2 swModel = (ModelDoc2)swApp.NewDocument(defaultTemplate, 0, 0, 0);
            if (swModel == null)
            {
                swModel = (ModelDoc2)swApp.ActiveDoc;
            }

            PartDoc swPart = (PartDoc)swModel;
            FeatureManager swFeatMgr = swModel.FeatureManager;

            swModel.SetTitle2("${partName}");

            // 3. Select Datum Plane: ${swPlaneName}
            Console.WriteLine("[*] Selecting datum plane: ${swPlaneName}...");
            bool selected = swModel.Extension.SelectByID2("${swPlaneName}", "PLANE", 0, 0, 0, false, 0, null, 0);
            if (!selected)
            {
                swModel.Extension.SelectByID2("Front Plane", "PLANE", 0, 0, 0, false, 0, null, 0);
            }

            // 4. Begin 2D Precision Sketch
            Console.WriteLine("[*] Generating 2D parametric sketch entities...");
            swModel.SketchManager.InsertSketch(true);
            swModel.ClearSelection2(true);

${sketchCode}

            // 5. Extrude 3D Solid Geometry
            // Depth: ${extrudeDepthMm} mm (${extrudeDepthM} m)
            Console.WriteLine("[*] Synthesizing 3D solid extrusion (depth: ${extrudeDepthMm} mm)...");
            swModel.ClearSelection2(true);

            int endCond = ${isSymmetric ? '(int)swEndConditions_e.swEndCondMidPlane' : '(int)swEndConditions_e.swEndCondBlind'};

            Feature swFeat = swFeatMgr.FeatureExtrusion3(
                true,                           // Sd: single directional
                false,                          // Flip
                false,                          // Dir: reverse
                endCond,                        // T1: End Condition Type
                0,                              // T2
                ${extrudeDepthM},               // D1: Depth in meters
                0,                              // D2
                false, false,                   // Dchk1, Dchk2: Draft
                false, false,                   // Ddir1, Ddir2: Draft Outward
                0, 0,                           // Dang1, Dang2: Draft Angles
                false, false,                   // OffsetRev1, OffsetRev2
                false, false,                   // TranslateSurface1, TranslateSurface2
                true,                           // Merge: Merge Result
                true,                           // UseFeatureScope
                true,                           // UseAutoSelect
                0, 0,                           // T0, StartOffset
                false                           // FlipStartOffset
            );

            // 6. Assign Material: ${materialName}
            try
            {
                swPart.SetMaterialPropertyName2("Default", "SolidWorks Materials", "${materialName}");
            }
            catch {}

            // 7. Rebuild and Isometric Fit View
            swModel.ShowNamedView2("*Isometric", 7);
            swModel.ViewZoomtofit2();
            swModel.ForceRebuild3(true);

            Console.WriteLine("[+] 3D Solid generated successfully in SolidWorks!");
        }
    }
}
`;
