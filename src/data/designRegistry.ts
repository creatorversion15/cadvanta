// Helper functions for easy querying
export function getDesignById(id: string): DesignRegistryItem | undefined {
  return DESIGN_REGISTRY.find((d) => d.id === id);
}

export function getPackById(packId: string): DesignPack | undefined {
  return DESIGN_PACKS.find((p) => p.id === packId);
}

export function getDesignsByPack(packId: string): DesignRegistryItem[] {
  const pack = getPackById(packId);
  if (!pack) return [];
  return DESIGN_REGISTRY.filter((d) => pack.designIds.includes(d.id));
}

export function getFreeDesigns(): DesignRegistryItem[] {
  return DESIGN_REGISTRY.filter((d) => d.access === 'FREE');
}

export function getPremiumDesigns(): DesignRegistryItem[] {
  return DESIGN_REGISTRY.filter((d) => d.access === 'PREMIUM');
}

